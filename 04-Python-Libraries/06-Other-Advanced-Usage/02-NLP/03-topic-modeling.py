class LSAModel:
    """
    Latent Semantic Analysis (LSA) implementation using Singular Value Decomposition.
    Best used with TF-IDF matrices.
    """
    
    def __init__(self, num_topics: int):
        self.num_topics = num_topics
        self.U: Optional[np.ndarray] = None
        self.Sigma: Optional[np.ndarray] = None
        self.VT: Optional[np.ndarray] = None
        
    def fit(self, X: np.ndarray) -> np.ndarray:
        """
        Fits the LSA model using NumPy's SVD.
        
        Args:
            X: Document-Term matrix (usually TF-IDF). Shape (D, V).
            
        Returns:
            Document-Topic matrix of shape (D, K).
        """
        print("[LSA] Performing Singular Value Decomposition...")
        # Full SVD
        # U shape: (D, D), S shape: (min(D, V),), VT shape: (V, V)
        U_full, S_full, VT_full = np.linalg.svd(X, full_matrices=False)
        
        # Truncate to num_topics (k)
        k = self.num_topics
        self.U = U_full[:, :k]
        self.Sigma = np.diag(S_full[:k])
        self.VT = VT_full[:k, :]
        
        # Document-topic matrix is U * Sigma
        doc_topic = np.dot(self.U, self.Sigma)
        return doc_topic
        
    def get_topics(self, feature_names: List[str], top_n: int = 5) -> List[List[Tuple[str, float]]]:
        """
        Extracts the top words for each topic.
        """
        topics = []
        for topic_idx, topic_vector in enumerate(self.VT):
            # Sort topic weights in descending order
            top_indices = np.argsort(topic_vector)[::-1][:top_n]
            topic_words = [(feature_names[i], topic_vector[i]) for i in top_indices]
            topics.append(topic_words)
        return topics


class NMFModel:
    """
    Non-Negative Matrix Factorization (NMF) implementation using 
    Multiplicative Update Rules. Best used with TF-IDF matrices.
    
    Ensures all topic weights and document representations are non-negative,
    making topics highly interpretable (parts-based representation).
    """
    
    def __init__(self, num_topics: int, max_iter: int = 200, tol: float = 1e-4):
        self.num_topics = num_topics
        self.max_iter = max_iter
        self.tol = tol
        self.W: Optional[np.ndarray] = None # Document-Topic
        self.H: Optional[np.ndarray] = None # Topic-Term
        
    def fit(self, V: np.ndarray) -> np.ndarray:
        """
        Fits the NMF model using Lee & Seung's Multiplicative Update rules.
        
        Args:
            V: Document-Term matrix. Shape (D, V). All elements must be >= 0.
            
        Returns:
            W: Document-topic matrix.
        """
        print("[NMF] Initializing W and H matrices...")
        D, V_cols = V.shape
        K = self.num_topics
        
        # Random initialization with non-negative values
        np.random.seed(42)
        self.W = np.random.rand(D, K)
        self.H = np.random.rand(K, V_cols)
        
        # Add small epsilon to avoid division by zero
        eps = 1e-9
        
        print("[NMF] Starting multiplicative updates...")
        for iteration in range(self.max_iter):
            # Update H (Topic-Term matrix)
            # H = H * (W^T * V) / (W^T * W * H + eps)
            numerator_H = np.dot(self.W.T, V)
            denominator_H = np.dot(np.dot(self.W.T, self.W), self.H) + eps
            self.H *= numerator_H / denominator_H
            
            # Update W (Document-Topic matrix)
            # W = W * (V * H^T) / (W * H * H^T + eps)
            numerator_W = np.dot(V, self.H.T)
            denominator_W = np.dot(self.W, np.dot(self.H, self.H.T)) + eps
            self.W *= numerator_W / denominator_W
            
            # Compute Frobenius norm of the reconstruction error to check for convergence
            if iteration % 50 == 0:
                error = np.linalg.norm(V - np.dot(self.W, self.H), 'fro')
                # Optional: check if error change is below tol to break early
                
        return self.W

    def get_topics(self, feature_names: List[str], top_n: int = 5) -> List[List[Tuple[str, float]]]:
        """Extracts top words for each topic."""
        topics = []
        for topic_idx, topic_vector in enumerate(self.H):
            top_indices = np.argsort(topic_vector)[::-1][:top_n]
            topic_words = [(feature_names[i], topic_vector[i]) for i in top_indices]
            topics.append(topic_words)
        return topics


class LDAGibbsSampler:
    """
    Latent Dirichlet Allocation (LDA) via Collapsed Gibbs Sampling.
    This is a true probabilistic generative model. Best used with raw BoW counts.
    
    Note: For a production environment, Variational Bayes (like in Gensim) or 
    highly optimized C++ Gibbs samplers (like Mallet) are preferred. This Python
    implementation is strictly for deep educational understanding.
    """
    
    def __init__(self, num_topics: int, alpha: float = 0.1, eta: float = 0.1, max_iter: int = 100):
        self.K = num_topics
        self.alpha = alpha  # Dirichlet prior on doc-topic distribution
        self.eta = eta      # Dirichlet prior on topic-word distribution
        self.max_iter = max_iter
        
    def fit(self, tokenized_docs: List[List[str]], vocab: Dict[str, int]) -> np.ndarray:
        """
        Fits the LDA model using Collapsed Gibbs Sampling.
        
        Args:
            tokenized_docs: List of documents, where each document is a list of string tokens.
            vocab: Mapping from token to integer ID.
            
        Returns:
            Document-Topic probability matrix theta (D x K).
        """
        print("[LDA] Initializing Gibbs Sampler state...")
        D = len(tokenized_docs)
        V = len(vocab)
        K = self.K
        
        # State tracking matrices
        # n_dk[d, k] = count of words assigned to topic k in document d
        self.n_dk = np.zeros((D, K), dtype=np.int32)
        # n_kw[k, v] = count of times word v is assigned to topic k
        self.n_kw = np.zeros((K, V), dtype=np.int32)
        # n_k[k] = total words assigned to topic k
        self.n_k = np.zeros(K, dtype=np.int32)
        
        # Word assignments: list of lists storing the topic assignment for each word in each doc
        self.Z = []
        
        # Random Initialization
        random.seed(42)
        for d in range(D):
            doc_topics = []
            for w_str in tokenized_docs[d]:
                if w_str not in vocab:
                    doc_topics.append(-1) # ignore out-of-vocab
                    continue
                
                v = vocab[w_str]
                # Randomly assign initial topic
                z = random.randint(0, K - 1)
                doc_topics.append(z)
                
                # Update counts
                self.n_dk[d, z] += 1
                self.n_kw[z, v] += 1
                self.n_k[z] += 1
                
            self.Z.append(doc_topics)
            
        print("[LDA] Starting Gibbs Sampling iterations...")
        for iteration in range(self.max_iter):
            # Iterate over all documents and all words
            for d in range(D):
                for i, w_str in enumerate(tokenized_docs[d]):
                    if w_str not in vocab:
                        continue
                        
                    v = vocab[w_str]
                    z = self.Z[d][i]
                    
                    # Decrement counts (remove this word from the current topic state)
                    self.n_dk[d, z] -= 1
                    self.n_kw[z, v] -= 1
                    self.n_k[z] -= 1
                    
                    # Calculate probabilities for sampling a new topic
                    # P(z_i = k | z_-i, w) \propto 
                    #   (n_dk + alpha) * (n_kw + eta) / (n_k + V * eta)
                    
                    # Vectorized computation for all K topics
                    p_z = (self.n_dk[d, :] + self.alpha) * \
                          (self.n_kw[:, v] + self.eta) / \
                          (self.n_k + V * self.eta)
                          
                    # Normalize to form a probability distribution
                    p_z /= np.sum(p_z)
                    
                    # Sample new topic from the distribution
                    new_z = np.random.choice(K, p=p_z)
                    
                    # Assign new topic and update counts
                    self.Z[d][i] = new_z
                    self.n_dk[d, new_z] += 1
                    self.n_kw[new_z, v] += 1
                    self.n_k[new_z] += 1
            
            if (iteration + 1) % 25 == 0:
                print(f"[LDA] Completed {iteration + 1}/{self.max_iter} iterations.")
                
        # Compute final document-topic distributions (Theta)
        # theta_{d, k} = (n_{d, k} + alpha) / (\sum n_{d, \cdot} + K * alpha)
        theta = np.zeros((D, K))
        for d in range(D):
            total_doc_words = np.sum(self.n_dk[d, :])
            theta[d, :] = (self.n_dk[d, :] + self.alpha) / (total_doc_words + K * self.alpha)
            
        # Compute final topic-word distributions (Phi)
        # phi_{k, v} = (n_{k, v} + eta) / (\sum n_{k, \cdot} + V * eta)
        self.phi = np.zeros((K, V))
        for k in range(K):
            self.phi[k, :] = (self.n_kw[k, :] + self.eta) / (self.n_k[k] + V * self.eta)
            
        return theta

    def get_topics(self, feature_names: List[str], top_n: int = 5) -> List[List[Tuple[str, float]]]:
        """Extracts top words for each topic based on the Phi matrix."""
        topics = []
        for k in range(self.K):
            topic_prob = self.phi[k, :]
            top_indices = np.argsort(topic_prob)[::-1][:top_n]
            topic_words = [(feature_names[i], topic_prob[i]) for i in top_indices]
            topics.append(topic_words)
        return topics


