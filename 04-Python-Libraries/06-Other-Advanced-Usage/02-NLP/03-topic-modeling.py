class CorpusManager:
    """
    Manages the document collection, builds vocabulary, and creates 
    Document-Term Matrices (DTMs) using Bag-of-Words (BoW) or TF-IDF.
    """
    
    def __init__(self):
        self.vocab: Dict[str, int] = {}
        self.reverse_vocab: Dict[int, str] = {}
        self.doc_frequencies: Dict[str, int] = defaultdict(int)
        self.num_docs = 0
        self.preprocessor = TextPreprocessor()
        
        # Store tokenized documents
        self.tokenized_docs: List[List[str]] = []
        
    def fit_transform(self, documents: List[str], use_tfidf: bool = False) -> np.ndarray:
        """
        Fits the vocabulary on the documents and transforms them into a DTM.
        
        Time Complexity: O(D * L) where D is number of docs, L is average doc length.
        Space Complexity: O(D * V) for the dense numpy array. In practice, sparse matrices are used.
        """
        self.num_docs = len(documents)
        self.tokenized_docs = [self.preprocessor.tokenize(doc) for doc in documents]
        
        # Build vocabulary and doc frequencies
        vocab_idx = 0
        for tokens in self.tokenized_docs:
            unique_tokens = set(tokens)
            for token in unique_tokens:
                self.doc_frequencies[token] += 1
                if token not in self.vocab:
                    self.vocab[token] = vocab_idx
                    self.reverse_vocab[vocab_idx] = token
                    vocab_idx += 1
                    
        vocab_size = len(self.vocab)
        
        # Create Document-Term Matrix (Dense for educational simplicity)
        dtm = np.zeros((self.num_docs, vocab_size), dtype=np.float64)
        
        for doc_id, tokens in enumerate(self.tokenized_docs):
            term_counts = Counter(tokens)
            for token, count in term_counts.items():
                if token in self.vocab:
                    col_idx = self.vocab[token]
                    
                    if use_tfidf:
                        # Term Frequency (TF)
                        tf = count / len(tokens) if tokens else 0
                        # Inverse Document Frequency (IDF) - smoothed
                        idf = math.log((1 + self.num_docs) / (1 + self.doc_frequencies[token])) + 1
                        dtm[doc_id, col_idx] = tf * idf
                    else:
                        # Bag of Words (BoW) count
                        dtm[doc_id, col_idx] = count
                        
        return dtm

    def get_feature_names(self) -> List[str]:
        """Returns the vocabulary ordered by index."""
        return [self.reverse_vocab[i] for i in range(len(self.vocab))]


