def cosine_similarity(vec1: np.ndarray, vec2: np.ndarray) -> float:
    """
    Helper function to compute cosine similarity between two vectors.
    """
    dot_product = np.dot(vec1, vec2)
    norm1 = np.linalg.norm(vec1)
    norm2 = np.linalg.norm(vec2)
    if norm1 == 0 or norm2 == 0:
        return 0.0
    return dot_product / (norm1 * norm2)

def interview_challenge_similar_documents(
    query_doc_idx: int, 
    doc_topic_matrix: np.ndarray, 
    top_k: int = 3
) -> List[Tuple[int, float]]:
    """
    Interview Challenge:
    Given a Document-Topic matrix (where rows are documents and columns are 
    topic distributions or weights), find the Top-K most similar documents 
    to a given query document.
    
    Approach:
    1. Extract the topic vector for the query document.
    2. Compute the cosine similarity between the query vector and all other doc vectors.
    3. Sort by similarity descending.
    4. Return the top_k indices and their similarity scores (excluding the query doc itself).
    
    Time Complexity: O(D * K + D log D) where D is number of docs, K is number of topics.
    Space Complexity: O(D) to store similarity scores.
    """
    print("\n--- Running Interview Challenge: Topic-based Document Similarity ---")
    
    D = doc_topic_matrix.shape[0]
    if query_doc_idx < 0 or query_doc_idx >= D:
        raise ValueError("Invalid query document index.")
        
    query_vector = doc_topic_matrix[query_doc_idx]
    
    similarities = []
    for d in range(D):
        if d == query_doc_idx:
            continue
        sim = cosine_similarity(query_vector, doc_topic_matrix[d])
        similarities.append((d, sim))
        
    # Sort descending by similarity score
    similarities.sort(key=lambda x: x[1], reverse=True)
    
    return similarities[:top_k]


