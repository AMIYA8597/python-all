# $10,000!$ is a number so large it breaks physics. ALL exact algorithms fail.
#
# The Solution: Approximation Algorithms!
# In the real world, we do not need the absolute mathematically perfect route. 
# We just need a route that is "Good Enough", calculated incredibly fast!
#
# The 2-Approximation MST Algorithm:
# If the city distances obey the Triangle Inequality (meaning a direct flight 
# from A to C is always faster or equal to A -> B -> C), we can use a brilliant 
# mathematical shortcut:
# 
# 1. Calculate the Minimum Spanning Tree (MST) of the graph using Prim's or Kruskal's.
# 2. Perform a Preorder DFS Traversal of the MST.
# 3. The path generated by that traversal is mathematically GUARANTEED to be 
#    no worse than exactly 2x the cost of the absolute perfect optimal tour!
#
# Time Complexity: $O(E \log V)$ (The speed of finding the MST).
# We solve the 10,000 city route in a fraction of a second, with a mathematical 
